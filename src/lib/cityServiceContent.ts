// ---------- Дефолты для отсутствующих в справочниках ----------

function cityProfile(city: City): CityProfile {
  const p = CITY_PROFILES[city.slug];
  if (p) return p;
  const mid = Math.ceil(city.districts.length / 2);
  return {
    climate: city.localContext,
    buildings: "смешанный жилой фонд — от старых панельных домов до современных новостроек, а также частный сектор и коммерческие помещения",
    logistics: `дежурная бригада ${city.nameLocative} с выездом в среднем за ${city.arrivalTime}`,
    sectors: ["УК и ТСЖ", "рестораны и общепит", "гостиницы", "частный сектор", "коммерческая недвижимость"],
    centerDistricts: city.districts.slice(0, mid),
    outerDistricts: city.districts.slice(mid),
  };
}

function serviceAngle(service: Service): ServiceAngle {
  const a = SERVICE_ANGLES[service.slug];
  if (a) return a;
  return {
    problem: service.intro,
    materials: `основные объекты для работы — ${service.objects.slice(0, 3).join(", ").toLowerCase()}`,
    seasonSouth: "в ЮФО заявки распределены круглый год с пиками в жаркий и дождливый сезоны",
    seasonKrym: "в Крыму заявки идут круглый год с усилением в межсезонье и перед курортным сезоном",
    scenarios: service.objects.slice(0, 4).map((o) => `${service.shortName.toLowerCase()} — ${o.toLowerCase()}`),
    audiences: [
      { title: "Собственники жилья", body: "полный цикл работ с гарантией и актом" },
      { title: "УК и ТСЖ", body: "плановое и аварийное обслуживание" },
      { title: "Коммерческая недвижимость", body: "работа в нерабочее время с документами" },
      { title: "Гостиничный сектор", body: "конфиденциальная работа без остановки объекта" },
    ],
  };
}

